# Some basic functionality of print function
#core concepts in print function
# 1. IF WE GIVE CONTINOUS COMMA IN A SINGLE LINE THEN PRINT FUNCTIN BY DEFAULT ADD SPACE IN BETWEEN AS FOLLOWS
print("Good morning","Harry","Carry on hurrry up")

#2. NOW SECOND THING TO BE NOTED THAT IF WE UE MULTIPLE TIMES THE PRINT FUNCTIONALITY THEN PRINT FINCTION AUTOMATICALLY WILL ENTER THE SYNTEX IN THE NEW LINE.

print("Harry is a coding lover")
print("He is also a keen learner")

# Making use of sep="" and end="" functionality
print("Good morning\n","Harry\n","Carry on hurrry up\n",sep="")

print("Harry is a coding over", end=",")
print("He is also a keen learner")