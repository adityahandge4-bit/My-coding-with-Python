tuples=(88,99,90,12,23,32,90,)
print(len(tuples)) # Use for finding the length of the tuples
print(tuples.count(9))# Use to find the no. of times does that number has arrived in the tuples
print(tuples.index(90))# use to index the given number or find its first occurence
print(min(tuples))# To find the minimum value among the tuples as listed above
print(max(tuples))# To find the maximum value among the tuples as listed above