def marks(**kwargs):
    for item in kwargs:
        print(f"The marks of {item} is {kwargs[item]}") # With the first turn it will write the item present inside the given data andd then it will run and will get the values from the given data
marks(shubham=56,Trisha=56,Thalapathy=100,Rajinikanth=100,Kamalhasan=120)